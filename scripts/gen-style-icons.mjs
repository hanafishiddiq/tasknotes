#!/usr/bin/env node
// Writes src/lib/style-icons.ts from the core's allow-list, so the picker
// imports exactly the icons the core accepts and nothing more (tree-shaken).
// Run after editing crates/tasknotes-core/src/style.json:
//   node scripts/gen-style-icons.mjs
// src/style-picker.test.tsx fails while the two disagree.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);
const { icons } = JSON.parse(readFileSync(new URL("crates/tasknotes-core/src/style.json", root), "utf8"));
const component = (name) => name.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join("");

const out = [
  "// Generated by scripts/gen-style-icons.mjs from crates/tasknotes-core/src/style.json. Do not edit.",
  "import type { LucideIcon } from \"lucide-react\";",
  "import {",
  ...icons.map((name) => `  ${component(name)},`),
  "} from \"lucide-react\";",
  "",
  "/** Every icon a List or Note Folder may take, by its Lucide name, in picker order. */",
  "export const STYLE_ICONS: Record<string, LucideIcon> = {",
  ...icons.map((name) => `  "${name}": ${component(name)},`),
  "};",
  "",
];
writeFileSync(new URL("src/lib/style-icons.ts", root), out.join("\n"));
console.log(`${icons.length} icons`);
